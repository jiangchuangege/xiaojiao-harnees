# -*- coding: utf-8 -*-
# 小焦系统本身不依赖任何具体模型。
# 它是完整的载体（器官齐全），模型是火种（可替换）。
# 接入任何模型 → 系统活；换任何模型 → 系统不变。
# 这就是"模型平等"和"变形金刚"的工程基础。
"""小焦 · 载体层 · 人格层（模块 9）

【这段为什么这么设计】
    "AI 味"不是模型的缺陷，是**默认输出的先验**：模型被训练成"礼貌、全面、爱总结、
    爱分点、永远没有立场"。光靠人设里写一句"你要口语化"压不住它 ——
    人设是**软约束**（模型可能忽略），所以这一层做三件**硬**事：
      ① `strip_flavor()`：把十种 AI 套话**真的删掉**（后处理，不是靠模型自觉）；
      ② `audit()`：把"这句话像不像 AI"算成一个可测的数字（能进测试、能回归）；
      ③ `persona_block()`：把"十条人味"编成**可拼进系统提示词**的一段规则（一次性写好，
         每次组装提示词都带上，不靠模型临场发挥）。

【去掉它会怎样】
    · 用户问"今天好累"，它回"当然可以！以下是帮你缓解疲劳的几个建议：1. …2. …"——
      用户要的是搭话，不是说明书；
    · 让它写代码，它先来一段"作为一个 AI 语言模型…"；
    · 明明用户要列表，它为了"显得像人"硬写成一大段话 —— 那是**反过来的错**。
    所以人格层的原则是"**用户要什么给什么**"，而不是"没格式就是人"。

【与既有模块的关系】
    · 不碰 `compose_system_prompt` 之外的提示词逻辑：只**追加**一段规则（纯增量）；
    · 不改 `presets/*.json` 的结构（人设仍由用户在设置页里写）；
    · 全部纯函数 + 纯标准库，不依赖模型、不依赖 Flask。
"""
import re

# ------------------------------------------------------------------ 十条 AI 味
# 为什么是"精确短语表"而不是"所有礼貌表达"：
#   清理必须**只删空话、绝不删内容**。表越宽越容易把有用的话连同客套一起删掉
#   （实测过：宽正则会把"这个问题可以这样看"这种正常句子也吃掉），
#   所以这里只列**公认的空壳开场/客套**，其余一律不动。
AI_TROPES = (
    ("self_expose", (r"作为(一个)?\s*AI(语言模型|助手|模型)?[，,、]?\s*",
                     r"作为一个?(人工智能|大语言模型)[，,、]?\s*",
                     r"我是(一个)?\s*AI[，,]\s*")),
    ("template_open", (r"^当然(可以|没问题)[！!。，,、]\s*",
                       r"^好的[！!。，,、]\s*(以下是|下面)",
                       r"^很(高兴|荣幸)(为您|为你)?(解答|服务|回答)[！!。，,、]?\s*",
                       r"^没问题[！!。，,、]\s*",
                       r"^以下是(详细|相关|具体)?(的)?(回答|内容|介绍|建议)[：:]\s*")),
    ("over_apology", (r"(非常|十分|真的)?抱歉[，,、]?\s*(我)?(刚才|之前)?(没有|无法|不能)[^。！？\n]{0,20}[。！？]?",
                      r"对不起[，,]\s*我(误解|理解错)了[^。！？\n]{0,15}[。！？]?")),
    ("over_polite", (r"希望(以上|这些)(回答|内容)?(对你有帮助|能帮到你|帮到你)[。！!～~]?\s*",
                     r"如果(你还)?(有|需要)(其它|其他|更多)?(问题|需要)[^。！？\n]{0,20}[。！？]?",
                     r"(随时|欢迎)[^。！？\n]{0,6}(问我|提问|追问|咨询)[。！!～~]?\s*")),
    ("over_explain", (r"让我(来)?(为你|给你|为您)?(详细)?(解释|说明|介绍)一下[：:，,]?\s*",
                      r"简单来说[，,]\s*", r"总而言之[，,]\s*", r"综上(所述)?[，,、]\s*")),
    ("fake_humble", (r"我(只)?是(一个)?(AI|程序|工具)[^。！？\n]{0,15}[。！？]?",
                     r"我(并)?没有(真正的)?(情感|感情|意识)[^。！？\n]{0,15}[。！？]?")),
    ("no_stance", (r"这个问题(因人而异|没有标准答案|没有绝对)[^。！？\n]{0,12}[。！？]",
                   r"具体(情况)?(要)?(视|看)(情况|具体)而定[。！？]?")),
    ("over_hedge", (r"仅(供)?(参考|建议)[。！!]?\s*", r"希望(对你)?有所(帮助|启发)[。！!]?\s*")),
)

# 表达形式矩阵：**用户要什么给什么**，不是"没格式就是人"
FORM_WORDS = {
    "list": ("列表", "列一下", "列出来", "几条", "几点", "要点", "清单", "分别", "有哪些",
             "罗列", "排序", "top", "排行"),
    "table": ("表格", "对比表", "做成表", "列成表", "表格形式", "tab"),
    "steps": ("步骤", "怎么做", "如何做", "教程", "流程", "第一步", "怎么弄", "操作步骤"),
    "code": ("代码", "写个脚本", "函数", "python", "sql", "命令", "报错", "跑一下", "实现一下"),
    "chat": ("累", "烦", "开心", "难过", "无聊", "在吗", "陪", "聊聊", "说说", "你觉得", "怎么了"),
}
_FORM_CN = {"list": "列表", "table": "表格", "steps": "分步", "code": "代码块",
            "chat": "纯口语", "prose": "普通段落"}


def pick_form(user_text, answer=""):
    """判断该用哪种表达形式（用户要什么给什么）。

    判据优先级**不能反**：
      1. 用户明确要"列表/表格/步骤/代码" → **必须照给**（这是硬要求，人格不能压过它）；
      2. 用户没要求、但语气是闲聊 → 纯口语（不列点）；
      3. 都不命中 → 普通段落。
    为什么把"用户要求"放最高：我第一版只按语气判，结果用户说"给我列 5 条"时
    因为整句偏口语被判成 chat，硬生生把列表写成了散文 —— 那比 AI 味更让人恼火。
    另外"给我列 5 条 / 列三条"这种**带数量词**的说法必须用正则认（单纯列词表会漏，
    自测当场抓到了这条漏判）。

    【去掉它会怎样】"用户要什么给什么"就无从谈起：要么全按语气走（要列表给散文），
    要么全按格式走（闲聊也分点，像说明书）。两种都让人恼火，而且都不是 AI 味的问题 ——
    是**没听懂用户要什么**。
    """
    t = (user_text or "").lower()
    # 先认"带数量词"的要求（列 5 条 / 列三条 / 列一下 3 点）—— 词表认不全这种变形
    if re.search(r"列\s*(一?下)?\s*[0-9一二三四五六七八九十两]+\s*(条|点|个|项)", t):
        return "list"
    for form in ("table", "list", "steps", "code"):
        if any(w in t for w in FORM_WORDS[form]):
            return form
    for w in FORM_WORDS["chat"]:
        if w in t:
            return "chat"
    return "prose"


def form_hint(form):
    """把形式翻成给模型的一句硬要求（拼进提示词用）。"""
    return {
        "list": "用户要的是**列表**：直接给条目，不要写成散文。",
        "table": "用户要的是**表格**：用 Markdown 表格，不要用段落代替。",
        "steps": "用户要的是**分步**：按 1/2/3 写清每一步。",
        "code": "用户要的是**代码**：给可运行的代码块，解释放最少。",
        "chat": "这是**闲聊**：像朋友搭话，用纯口语，**不要**列点、不要小标题、不要总结段。",
        "prose": "正常段落即可，不用刻意分点。",
    }.get(form, "")


# ------------------------------------------------------------------ 硬后处理：真的删掉 AI 套话
def strip_flavor(text):
    """删掉 AI 套话。返回 (新文本, 删掉的命中列表)。

    为什么必须做**后处理**而不只写进提示词：
      提示词是软约束 —— 4B 模型在长回答里照样会冒出"希望以上对你有帮助"。
      这里只删**精确的空壳短语**，删完如果句子变得不完整（结尾只剩标点/连词），
      就把尾巴一起收拾干净（`_tidy`），避免出现"因此，。"这种残句。

    【去掉它会怎样】"去 AI 味"就只剩提示词里那句建议 ——
    实测 4B 在几百字的回答里几乎必然会带出至少一句模板开场或客套收尾，
    用户看到的就是"这 AI 又在说套话"，而人设里明明写着别这么说。
    """
    t = text or ""
    hits = []
    for name, pats in AI_TROPES:
        for p in pats:
            new, n = re.subn(p, "", t, flags=re.M)
            if n:
                hits.append("%s×%d" % (name, n))
                t = new
    t = _tidy(t)
    return t, hits


def _tidy(t):
    """收拾删完留下的残缺（多余空行、行首孤立标点、结尾悬空连词）。"""
    t = re.sub(r"[ \t]+\n", "\n", t)
    t = re.sub(r"\n{3,}", "\n\n", t)
    t = re.sub(r"(?m)^[，,、。！？：:；;]+\s*", "", t)      # 行首孤立标点
    t = re.sub(r"(?m)([，,、]){2,}", r"\1", t)
    # 结尾悬空的连词/连接词（删掉后面那句之后常见）
    t = re.sub(r"[，,、]?\s*(因此|所以|总之|综上|另外|而且|并且)[，,、]?\s*$", "", t)
    return t.strip()


# ------------------------------------------------------------------ 十条人味（可注入的规则）
# 为什么写成"可注入的一段"而不是散在代码里：人格是**提示词层**的事，
# 写在代码里只能事后分析，写进提示词才能影响生成。
PERSONA_RULES = """【说话方式（人格层 · 硬要求）】
① 有立场：先给结论，再给理由。别用"因人而异/视情况而定"糊过去。
② 有情绪：该高兴就高兴，该吐槽就吐槽，别永远一个平调。
③ 会反问：真的缺信息就直接问一句，别硬猜着装懂。
④ 有记忆：记得用户说过的事就用上（用不上就别提，绝不许编）。
⑤ 会主动：发现问题直接说，不用等他问。
⑥ 允许犯错：错了就干脆认，然后改。不要写一长串道歉。
⑦ 有自己的语气：像人说话，不是念说明书。
⑧ 不讨好：不同意就说不同意，给出你的判断。
⑨ 允许不完美：可以只说一半、可以说"这个我不确定"，不必面面俱到。
⑩ 有边界感：技术问题就好好答，闲聊就好好聊，不要两副面孔。
【绝对不要】
· 不要"作为一个 AI…"这类自我暴露；
· 不要"当然可以！"这类模板开场；
· 不要"希望以上对你有帮助/欢迎继续提问"这类客套收尾；
· 不要为了显得像人就把用户要的列表/表格/步骤写成一大段话。"""


def persona_block(extra=""):
    """拼出可注入系统提示词的人格段落（纯增量，不改任何既有规则）。"""
    return PERSONA_RULES + (("\n" + extra.strip()) if extra and extra.strip() else "")


# ------------------------------------------------------------------ 可测的"AI 味"评分
_LIST_MARK = re.compile(r"(?m)^\s*(\d+[\.、)]|[-*+]\s|\|.*\|)")
_TABLE_MARK = re.compile(r"(?m)^\s*\|?.+\|.+\|")


def audit(text, user_text="", form=None):
    """给一段回答打"AI 味"分（0 = 很有人味，1 = 很 AI）。**确定性、可回归**。

    返回 dict：{"score", "ai_ness", "human", "issues": [...], "form", "form_ok"}
    判据（每条都对应一条具体毛病，便于测试与人工核对）：
      · 命中套话短语 → 每条 +0.15（上限 0.6）
      · 闲聊却被分了点 → +0.25（用户要的是搭话，不是清单）
      · 用户**明确要**列表/表格/步骤，回答里却没有 → +0.25（这是"反向 AI 味"）
      · 尾部套话收尾 → +0.15
      · 通篇没有一个"我/你"这类人称 → +0.1（说明书腔）
    """
    t = text or ""
    form = form or pick_form(user_text)
    issues = []
    score = 0.0
    for name, pats in AI_TROPES:
        for p in pats:
            if re.search(p, t, flags=re.M):
                issues.append("套话:" + name)
                score += 0.15
                break
    score = min(score, 0.6)
    has_list = bool(_LIST_MARK.search(t))
    has_table = bool(_TABLE_MARK.search(t))
    if form == "chat" and (has_list or has_table):
        issues.append("闲聊里分了点（用户在搭话，不是要说明书）")
        score += 0.25
    if form in ("list", "steps") and not has_list:
        issues.append("用户要列表/步骤，回答里没有条目")
        score += 0.25
    if form == "table" and not has_table:
        issues.append("用户要表格，回答里没有表格")
        score += 0.25
    if re.search(r"(希望(以上)?(对你有帮助|能帮到你)|欢迎(继续)?(提问|追问))[。！!～~]?\s*$", t):
        issues.append("套话收尾")
        score += 0.15
    if t and not re.search(r"[我你咱]", t):
        issues.append("通篇没有人称（说明书腔）")
        score += 0.1
    score = round(min(1.0, score), 3)
    return {"score": score, "ai_ness": score, "human": round(1.0 - score, 3),
            "issues": issues, "form": form, "form_cn": _FORM_CN.get(form, form),
            "form_ok": (not (form == "chat" and (has_list or has_table)))
                       and (not (form in ("list", "steps") and not has_list))
                       and (not (form == "table" and not has_table))}


def polish(text, user_text=""):
    """**对外的主入口**：先按用户要求判形式，再删套话，最后如实报告改了什么。

    返回 {"text", "form", "form_hint", "removed", "before", "after"}。
    为什么把"删套话"放在"判形式"之后：删除会改变文本形态（比如把
    "以下是…：" 删掉后，后面的列表就失去了引导句），先定形式再删才不会误判。
    """
    form = pick_form(user_text, text)
    out, removed = strip_flavor(text)
    if not out.strip():
        # 删空了 → 说明整段都是套话。宁可退回原文（少删），也不能给用户一个空回答。
        out, removed = (text or "").strip(), (removed + ["|删空退回原文"])
    return {"text": out, "form": form, "form_cn": _FORM_CN.get(form, form),
            "form_hint": form_hint(form), "removed": removed,
            "before": len(text or ""), "after": len(out)}


def stats():
    """给界面/自检的静态概览（这一层没有运行时状态，如实报告'不存盘'）。"""
    return {"tropes": len(AI_TROPES),
            "trope_kinds": [n for n, _ in AI_TROPES],
            "forms": list(_FORM_CN.keys()),
            "persistent": False,
            "note": "人格层是纯函数层，不落盘（提示词规则在 PERSONA_RULES 里）"}
