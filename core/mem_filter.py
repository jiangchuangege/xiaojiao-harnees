# -*- coding: utf-8 -*-
# 小焦系统本身不依赖任何具体模型。
# 它是完整的载体（器官齐全），模型是火种（可替换）。
# 接入任何模型 → 系统活；换任何模型 → 系统不变。
# 这就是"模型平等"和"变形金刚"的工程基础。
"""小焦 · 载体层 · 对话记忆的**写入侧过滤**（修一 + 修二）

【它解决什么 —— 实测症状】
  用户问「你还记得上一次吗」，它答：
  「我记不起上一次我们聊了什么 —— 不过，我确实记得一些**你曾经提到过的内容**：…哔哩哔哩…」
  那句"你曾经提到过"里的东西**根本不是用户说的**，而是**抓取结果的残留**被存进了记忆。
  这一条的严重性高于"检索不准"：**它把「工具给的」说成了「用户说的」**。

  实测从真实记忆库里清出 253 条污染，其中：
    · 抓取结果头（`🌐 **URL** · HTTP 200 <原始正文>`）194 条
    · 载体的抓取守卫提示（`⚠️ 抓取失败` / `⚠️ **可能幻觉**` / `✅ 抓取成功`）54 条
    · 坏回复 5 条：`<think>` 未闭合残留、**系统提示词整段泄漏进回答**、
      整条就是 `⏳ 正在调用工具…` 占位符、`（已回答）` 占位符、
      以及那句把来源说错的「你曾经提到过」。
  清理是治标；**这里治的是源头**：往后这类东西**根本写不进去**。

【两条硬规则（对应规格的硬性规则 1、2）】
  规则 1 · 工具原始返回**绝不进**对话记忆；
  规则 2 · 坏回复（占位符／未闭合／半截／空）**绝不进**记忆。

【为什么不是"发现工具痕迹就整条不存"】
  实测那一轮对话里，**工具原始返回**和**它自己说的话**是**粘在同一行**的：
  `🌐 **https://…** · HTTP 200 <抓到的正文> 📖 **小焦解读** 这是一个返回 JSON 数据的网页…`
  整条丢掉 = 把它自己的那句解读也丢了。所以分两步：
    ① 先**剥掉工具渲染段**（🌐 到 📖 之间的原始正文、守卫提示行、结果表）；
    ② 剥完**还剩真内容**就存，**剥完只剩空壳**就整轮不存。
  这样"工具原始返回"一个字都进不去，而它自己说的话留得下来。

【`_ask` 为什么不用"看一眼像不像"的模糊判据】
  判据全部是**确定性的正则**，可单测、可复现；没有"调用模型判断"这一步 ——
  写入路径上多一次模型调用既慢又会引入不确定，而这里要的恰恰是"绝不漏"。
"""
from __future__ import annotations

import re

__all__ = ["BAD_PATTERNS", "TOOL_RENDER_PATTERNS", "MIN_KEEP",
           "is_bad_reply", "strip_tool_render", "clean_answer", "clip", "render"]

# ── 规则 2：坏回复（整轮不存）───────────────────────────────────────
BAD_PATTERNS = [
    (r"</?think>", "未闭合/残留 think 标签"),
    (r"【系统指令】", "系统提示词泄漏进回答"),
    (r"角色：\s*小焦[\s\S]{0,80}?工具：\s*list_files", "系统提示词片段泄漏"),
    (r"^\s*⏳\s*__pending__\s*$", "占位符 ⏳__pending__"),
    (r"^\s*（已回答）\s*$", "占位符「（已回答）」"),
    (r"你曾经提到过", "把「它说的」说成「你提到过」的坏回复"),
    (r"^\s*（小脑正在检索[\s\S]{0,80}?）\s*$", "整条回复只是检索占位符（没有正文）"),
]

# ── 规则 1：工具渲染段（剥掉，不整轮丢）─────────────────────────────
TOOL_RENDER_PATTERNS = [
    # 【先剥"抓取进行中"那整句】`⏳ 正在抓取 <url>（忽略 robots 协议） ✅ 抓取成功！`
    #   必须在下面那条通用的 ⏳ 规则**之前** —— 通用规则只吃 40 字，
    #   这一句带 URL 往往超过 40 字，会留下一截尾巴（实测踩过）。
    r"[⏳]*\s*正在抓取[\s\S]{0,300}?✅\s*抓取成功[！!]?",
    # `🌐 **URL** · HTTP 200 <原始正文> 📖 **小焦解读**`：
    # 连**原始正文**一起剥到 `📖` 为止（正文可能就是整页 HTML）。
    r"🌐\s*\*\*[\s\S]*?(?=📖|\Z)",
    r"📖\s*\*\*小焦解读\*\*",
    # 载体的抓取守卫/状态提示（它们**不是模型的话**）
    r"⚠️\s*\*\*可能幻觉\*\*[^\n]*",
    r"⚠️\s*抓取失败[^\n]*",
    r"⚠️\s*删除操作被载体层拦截[^\n]*",
    r"✅\s*抓取成功[！!]?",
    # 「⏳ 正在<做事>…」这个**等待提示**：只剥那**一小句**，后面的正文要留下。
    # 【为什么不能写成 `^\s*⏳[^\n]*$` 整行删】实测流水线会把等待提示**粘在真回答前面**
    #   （同一条消息里），整行删会把真内容一起删掉 —— 实测有 18 条正是这个形状：
    #   「⏳ 正在用物理学思维拆解公司现金流... 现金流 = 一个动态能量系统…」。
    # 判据：从 ⏳ 起，吃掉"不超过 40 字、且不含句末标点"的那一段，再吃掉紧跟的 `...`/`。`。
    #   于是「⏳ 正在调用工具：net_ip（查 IP 归属地）」被整个吃掉（它本身就是全部内容），
    #   而「⏳ 正在用物理学… ... 现金流 = …」只吃掉提示那一句。
    r"^\s*⏳[^\n。.…]{0,40}[。.…]{0,3}\s*",
    r"^\s*（小脑正在检索[^\n）]{0,60}）\s*",
    r"⏳\s*检索完成[。.．]?\s*",
    r"^\s*📖\s*",                  # 单独的解读标记
]
# ⚠️ **不要**用"行里有竖线就当表格删掉"这种判据 —— 实测它会把**模型自己写的
#    Markdown 表格**一起吃掉（它经常用表格回答）。抓取结果的表只有一种：
#    `📋 **页面结构速览**` 之后紧跟的那一块，所以**只删那一块**。
_TABLE_BLOCK = re.compile(r"📋\s*\*\*页面结构速览\*\*[\s\S]*?(?=\n[ \t]*\n|\Z)")

# 剥完还剩多少字才算"有真内容"。4 个字：小于这个数存进去也只是噪声。
MIN_KEEP = 4


def is_bad_reply(text):
    """规则 2 判据。返回 `(是否坏回复, 为什么)`。

    空 / 只有一个占位符 / 未闭合 think / 系统提示词泄漏 / 未闭合代码块 —— 都算坏。
    """
    t = (text or "").strip()
    if not t:
        return True, "空回答"
    for pat, why in BAD_PATTERNS:
        if re.search(pat, t, re.M):
            return True, why
    # 半截：代码围栏数为奇数 → 有一个 ``` 没闭合（生成被打断了）
    if t.count("```") % 2 == 1:
        return True, "半截（代码块未闭合）"
    # 半截：`<think` 开了没闭（上面 `</?think>` 已覆盖闭合那种，这里兜只有开标签的）
    if "<think" in t and "<｜end▁of▁thinking｜>" not in t:
        return True, "半截（think 未闭合）"
    return False, ""


def strip_tool_render(text):
    """规则 1：剥掉工具渲染段，只留它自己说的话。"""
    t = text or ""
    t = _TABLE_BLOCK.sub(" ", t)          # 先干掉抓取结果表（只删那一块）
    for pat in TOOL_RENDER_PATTERNS:
        t = re.sub(pat, " ", t, flags=re.M)
    # 清掉剥完留下的空行与多余空白
    t = re.sub(r"[ \t]{2,}", " ", t)
    t = re.sub(r"\n{2,}", "\n", t)
    return t.strip()


def clean_answer(text):
    """写入前**唯一**的判据入口。返回 `(能存的文本, 说明)`；不能存时文本为空串。

    先按规则 2 整轮否决；否则按规则 1 剥掉工具渲染段，剥完太短就当没内容。
    """
    bad, why = is_bad_reply(text)
    if bad:
        return "", "不进记忆（坏回复：%s）" % why
    cleaned = strip_tool_render(text)
    # 剥完可能只剩标点/记号 —— 去掉它们再量长度
    bare = re.sub(r"[\s，。！？；：、,.!?;:\-—…*#>`\[\]()（）]+", "", cleaned)
    if len(bare) < MIN_KEEP:
        return "", "不进记忆（剥掉工具渲染段后没有真内容）"
    if cleaned == (text or "").strip():
        return cleaned, "照常进记忆"
    return cleaned, "进记忆（已剥掉工具渲染段）"


def clip(text, limit=200):
    """把长回答截到 `limit` 内 —— 但**尽量切在句末**，别把话截成半截。

    【为什么必须这样切】实测：直接 `text[:200]` 会把一条回答切在 URL 中间
    （`…可直接在浏览器地址栏输入 \\`https://htt`），存进记忆就是一条**半截**记录。
    规则 2 说"半截绝不进记忆"，那"自己截出来的半截"当然也算。
    切点太靠前（不足一半）就别硬切，宁可留满 —— 那样至少信息没被腰斩。
    """
    t = (text or "").strip()
    if len(t) <= limit:
        return t
    head = t[:limit]
    cut = max(head.rfind("。"), head.rfind("！"), head.rfind("？"),
              head.rfind("；"), head.rfind("\n"))
    if cut >= limit // 2:
        return head[:cut + 1].strip()
    return head.strip()


def render():
    """给上下文/面板用的一句事实（不含结论）。"""
    return {"bad_patterns": [w for _, w in BAD_PATTERNS],
            "tool_render_patterns": len(TOOL_RENDER_PATTERNS),
            "min_keep": MIN_KEEP}
