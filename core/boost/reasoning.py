# ------------------------------------------------------------------ 追加部分（内存 + 落盘）
# 【为什么用 dict 而不是 list 存追加部分】
#   追加本质上是「按 id 覆盖」（同 id 后写的赢），dict 是唯一天然表达这个语义的结构；
#   用 list 的后果是每次 add 都要先扫一遍找同 id 再替换，写错一次就出现
#   **同一个 id 在库里存在两份**，之后 pick 选到哪一份取决于遍历顺序 —— 不可复现。
#   Python 3.7+ 的 dict 保序，所以「追加顺序」也同时被保住了。
_EXTENDED = {}
_LOADED = False          # 是否已经从磁盘读过（只读一次，见 _ensure_loaded）


def _ensure_loaded():
    """首次被用到时，把 `logs/boost/templates.json` 的追加部分读进内存（**只读一次**）。

    【为什么必须自动加载，而不是等上层显式调 load_extended()】
        「越用越大」要求的是**跨进程**也生效：昨天追加的模板，今天重启后必须还在。
        如果只有显式调用才加载，那么所有没调它的进程都看不见磁盘上的追加，
        表现为「模板明明存了，重启就没了」—— 用户会以为系统在骗他。
    【为什么先置位 `_LOADED` 再读文件】
        读文件万一出意外，也不会让后续每次 pick() 都重读一遍磁盘
        （那会把一次对话变成十几次文件 IO）；置位在前，失败也只失败一次。
    """
    global _LOADED
    if _LOADED:
        return
    _LOADED = True
    try:
        for t in load_extended():
            tid = norm(t.get("id"))
            if tid:
                _EXTENDED[tid] = t
    except Exception:      # noqa: silent-ok — 读不动就当「还没有追加过」，绝不能拖垮 import
        pass


def _copy_template(t):
    """返回模板的**深副本**（调用方改副本绝不能污染库里的原件）。

    【为什么是深拷贝而不是 `dict(t)`】
        模板里有 steps / pitfalls / keywords 三个列表，`dict(t)` 只复制外层：
        调用方一句 `t["steps"].append("x")` 就把库改了。这类污染**不会报错**，
        只会让「下一个问题用的模板莫名其妙多了一条步骤」，
        排查时你会去怀疑模型，而真凶在三个调用点之前。
    """
    if not isinstance(t, dict):
        return {}
    try:
        return copy.deepcopy(t)
    except Exception:      # noqa: silent-ok — 值都是普通 str/list，理论上不会失败；真失败也别抛
        return dict(t)


def _kw_weight(w):
    """单个命中词的权重：按**词长**加权。

    【为什么这么定】
        2 字及以下（从、像、由）在中文里到处都是，诊断力最弱 → 1.0；
        3 字（为什么、不变量）已经带有指向性 → 1.5；
        4 字及以上（有多少种、第一性、状态转移）几乎只在对应类型的问题里出现 → 2.0。
    【去掉它（全部算 1.0）会怎样】
        一张塞满短字的关键词表会**永远赢**选型，而它并不是更相关，
        只是更容易被随便一句话碰到 —— 这正是「选错了还显得很有道理」的成因。
    """
    s = norm(w)
    n = len(s)
    if n <= 2:
        return 1.0
    if n == 3:
        return 1.5
    return 2.0


def _as_list(v):
    """把任意输入规整成「非空字符串构成的列表」。

    【为什么字符串要变成单元素列表】
        手写 JSON 时把 steps 写成一行字符串是极常见的手误，
        这时它显然就是「一条步骤」：包成 `[v]` 比丢掉更符合本意（丢掉等于用户白写）。
    【为什么 None / 其它类型返回 []】
        规格要求「至少是空列表」，而「没有步骤」本身是合法状态；
        返回 None 会让下游 `for s in t["steps"]` 直接 TypeError ——
        而本模块的硬要求是**任何函数都不许因为输入异常而抛**。
    """
    if v is None:
        return []
    if isinstance(v, str):
        s = v.strip()
        return [s] if s else []
    if isinstance(v, (list, tuple)):
        out = []
        for x in v:
            s = x.strip() if isinstance(x, str) else norm(x)
            if s:
                out.append(s)
        return out
    s = norm(v)          # 数字/其它 → 转成字符串，仍然保留信息
    return [s] if s else []


def _fill(t):
    """把一条模板补齐成完整结构（缺字段补默认值），**就地修改**并返回同一个 dict。

    【为什么只对「我们自己拥有的 dict」调用它】
        就地修改很危险，所以调用点只有两个：add() 里刚拷出来的副本、
        load_extended() 里刚从 JSON 反序列化出来的新对象 —— 都不会碰到内置表。
    【去掉它会怎样】
        一条手写不完整的追加模板会带着缺字段进库，render() 就会
        在 `t["steps"]` 上 KeyError；而这条模板是用户自己加的，
        他只会看到「我加完以后整个功能就坏了」，却不知道坏在哪。
    """
    tid = norm(t.get("id"))
    t["id"] = tid
    for k in ("name", "name_en"):
        v = norm(t.get(k))
        t[k] = v if v else tid
    v = norm(t.get("when"))
    t["when"] = v if v else "（未填写适用场景，按关键词自动选型）"
    t["steps"] = _as_list(t.get("steps"))
    t["pitfalls"] = _as_list(t.get("pitfalls"))
    t["keywords"] = _as_list(t.get("keywords"))
    return t


_ID_RE = re.compile(r"^[a-z][a-z0-9_]*$")


def _valid_id(v):
    """合法 id：英文蛇形小写，且必须以字母开头。不合法返回空串（由调用方兜底）。

    【为什么要卡这么死】
        id 会被写进 `templates.json`、被上层当字符串传进 render()、
        也会成为日志里那一列。允许中文/空格/大写之后，
        必然出现「我明明加过归纳，pick 却说没有」这种**看起来像丢了数据**的假故障。
    """
    s = norm(v)
    return s if _ID_RE.match(s) else ""


def _fallback_id(src):
    """给一个缺失/非法的 id 造一个**可用且不冲突**的兜底 id。

    【为什么宁可用兜底 id 也不抛异常】
        规格硬要求「绝不抛」。而且这里抛异常的后果格外糟：
        上层是在「用户刚加了一条模板」的时刻调它的，
        抛出去等于**把用户刚写的东西整条丢掉**，而它其实只差一个合法的 id。
    【为什么用 name/name_en 推导而不是直接用序号】
        直接用 `ext_1`、`ext_2` 的话，日志里只看得到一个数字，
        事后无法判断这条是「量纲检验」还是别的 —— 能从名字推导就先推导，
        实在推导不出来（比如 id 是中文、名字也空）才退回 `ext`。
    """
    raw = norm(src.get("id")) or norm(src.get("name_en")) or norm(src.get("name"))
    s = re.sub(r"[^0-9a-zA-Z_]+", "_", raw).strip("_").lower()
    s = s[:40]
    if not s or not s[0].isalpha():
        s = ("ext_" + s) if s else "ext"
    if not _ID_RE.match(s):
        s = "ext"
    existing = _builtin_ids() | set(_EXTENDED.keys())
    cand, n = s, 1
    while cand in existing:
        n += 1
        cand = "%s_%d" % (s, n)
    return cand


def _merged_raw():
    """内置 + 追加的合并结果（**内部用，不做副本**，调用方只许读不许改）。

    【顺序为什么是「内置先、追加后」】
        选型同分时按「先出现者胜」，让内置模板在同分时赢过追加模板：
        内置表是经过筛选的通用套路，追加表是用户自己的偏好，
        平手时先用通用套路更不容易出错。
    【同 id 为什么追加赢】
        追加 = 「我要覆盖这条」，这是 add() 的公开语义；
        内置赢的话，用户永远改不动一条他不满意的内置模板 —— 那「越用越大」就白说了。
    """
    out = []
    for t in TEMPLATES:
        ext = _EXTENDED.get(t.get("id"))
        out.append(ext if ext is not None else t)
    builtin = _builtin_ids()
    for tid, t in _EXTENDED.items():
        if tid not in builtin:
            out.append(t)
    return out


def _find(template_id):
    """按 id 找模板（先看追加、再看内置；都找不到返回 None）。"""
    tid = norm(template_id)
    if not tid:
        return None
    _ensure_loaded()
    t = _EXTENDED.get(tid)
    if t is None:
        t = _BY_ID.get(tid)
    return t


def _matched_rules(q):
    """返回命中的句式规则列表：[(原文里最先出现的触发词, 目标 id 元组, 加分, 中文理由)]。

    【为什么先用 has_any 再取 hits】
        has_any 是布尔快路径（绝大多数规则不命中，只做一次子串判断就够），
        而「理由」需要具体是哪个词命中的 —— 只在命中时才去取，
        取的时候又用 hits() 保证拿到的是**原文里最先出现的那一个**，
        这样日志里的理由读起来和原文顺序一致，不像乱说的。
    """
    out = []
    for words, targets, bonus, why in _PATTERN_RULES:
        if has_any(q, words):
            m = hits(q, words)
            out.append((m[0] if m else "", targets, bonus, why))
    return out


def _why(t, kw, rules, q):
    """生成「为什么选它」的中文理由，**必须引用命中的关键词**（日志要能自查）。

    【为什么这个理由值得占一行代码】
        pick() 是纯规则判的，规则判错时唯一的线索就是这条理由。
        不写它的话，事后只能看到「选了归纳」这一个结果，
        无法回答「为什么不是演绎」—— 而调整判定规则必须从这个问题开始。
    """
    parts = []
    if kw:
        parts.append("命中关键词「%s」" % "」「".join(kw[:3]))
    if rules:
        r = rules[0]
        seg = "句式上%s" % r[3]
        if r[0]:
            seg += "（原句里出现「%s」）" % r[0]
        parts.append(seg)
    if not parts:
        parts.append("没有任何命中，但它是当前得分最高的模板")
    tail = "，所以在 %d 个模板里选「%s」。" % (len(_merged_raw()), t.get("name") or t.get("id"))
    return "；".join(parts) + tail


# ------------------------------------------------------------------ ① 选型
def pick(question):
    """**纯规则**选型：给一个问题挑出最合适的一个推理模板；挑不出来返回 `None`。

    判分方式（全部可复现：没有随机、没有 hash、没有集合迭代顺序）：
      1. 对每个模板，用 `hits(question, t["keywords"])` 取命中词，
         每个命中按词长加权累加（见 `_kw_weight`）；
      2. 再叠加**句式规则**（`_PATTERN_RULES`）的加分：含「为什么」→第一性原理、
         含「最好/该不该」→成本收益、含「证明」→反证、含「有多少种」→枚举、
         含「最短/最快」→贪心、含「一定/必然」→演绎 等等；
      3. 得分最高者胜；**同分时按模板在库里的先后顺序取前一个**（内置优先于追加）。

    返回该模板的**副本**，并额外加上：
      score  浮点得分
      why    中文说明为什么选它（引用命中的关键词）
    原有 id / name / name_en / when / steps / pitfalls / keywords 全部保留。

    【为什么没有信号时必须返回 None，不许硬塞】
        见模块 docstring：选错模板会让模型「认认真真地把错事做完整」，
        输出看起来更专业、更难被发现。宁可交回 None 让上层接手。
        硬要求：`pick(None)`、`pick("")`、`pick("嗯嗯")` 全是 None。
    【为什么选完要 note() 一条流水】
        这就是「越用越大」的**证据**：日志里能数出哪一类推理被用了多少次，
        进而知道该补哪一类模板。不记的话，「越用越大」就只是一句口号。
    """
    _ensure_loaded()
    q = norm(question)
    if not q:
        return None
    # 纯寒暄 / 无实义输入：少于两个汉字且极短 → 不可能带推理信号，直接交白卷。
    # 为什么用 cjk_count 而不是 len：len("ok") 和 len("在吗") 都是 2，
    # 但后者是一句完整的追问、前者只是应答，用字符数会把两者等同看待。
    if cjk_count(q) < 2 and len(q) < 4:
        return None
    rules = _matched_rules(q)
    best, best_score, best_kw, best_rules = None, 0.0, [], []
    for t in _merged_raw():
        kw = hits(q, t.get("keywords") or [])
        s = sum(_kw_weight(w) for w in kw)
        rs = [r for r in rules if t.get("id") in r[1]]
        s += sum(r[2] for r in rs)
        if s > best_score:          # 严格大于：同分时先出现的赢（确定性的一部分）
            best, best_score, best_kw, best_rules = t, s, kw, rs
    if best is None or best_score <= 0:
        return None             # 没有任何推理信号 —— 绝不硬塞
    out = _copy_template(best)
    out["score"] = float(round(best_score, 3))
    out["why"] = _why(best, best_kw, best_rules, q)
    try:
        note("pick", id=best.get("id"), score=out["score"])
    except Exception:      # noqa: silent-ok — 流水记不上绝不能影响选型结果本身
        pass
    return out


# ------------------------------------------------------------------ ② 渲染
def render(template_id, question):
    """把模板渲染成**给模型的提示词**：分步指令 + 必须避免的坑 + 原问题原文。

    输出固定包含：推理类型、适用场景、编号的 steps、作为「必须避免」的 pitfalls、
    问题原文，以及最后的作答要求 —— **必须分步作答并标出每一步的依据**。
    这条收尾要求不能省：模型默认会给一段整体答案，
    只有明确要求「每一步标依据」，它的输出才能被 10.7 consistency 逐句核对。

    【template_id 不存在时怎么办 —— 两个选项里选了哪一个】
        规格给了两个选项，这里选**第一个：返回一段「找不到该模板」的提示词**，
        并在里面说明当前可用模板数量；同时把 `question` 原文附在后面。
        理由（也见模块 docstring）：静默退化会把「上层传错 id」永久藏起来，
        而 id 拼错是必然会发生的代码错误，必须当场可见；
        但只报错不留问题又会让这一轮对话没法继续（模型会对着报错文本开始编），
        所以顺手附上原问题、请它按普通方式作答，并**明令不许假装用了某个模板**。
    【question 为 None / 空串时】
        照渲染，位置填「(空问题)」。为什么不早退回 None：
        render 的返回值是给模型的提示词，返回 None 会让调用方拿去拼字符串时崩掉，
        而「问题为空」在真实链路上是正常状态（用户只发了一个「？」）。
    """
    tid = norm(template_id)
    q = norm(question)
    t = _find(tid)
    if t is None:
        n = len(_merged_raw())
        lines = [
            "【推理模板缺失】",
            "载体里没有 id 为「%s」的推理模板，当前可用模板共 %d 个。" % (tid or "(空)", n),
            "原因多半是上层传错了 id（拼写不一致，或这条模板还没被 add() 进来）。",
            "下面直接给出原始问题，请按普通方式作答 —— 但**不要假装自己用了某个模板**，",
            "也不要编造「按第 3 步」这类并不存在的步骤。",
            "",
            "【问题】",
            q or "(空问题)",
            "",
            "【作答要求】",
            "1) 先用自己的话复述一遍问题，确认你理解的是同一件事；",
            "2) 再分步作答，每一步都要标出依据（依据哪条已知、哪条假设、哪一步计算）；",
            "3) 最后单独写一句：这几步里最可能错在哪里。",
        ]
        return "\n".join(lines)
    steps = t.get("steps") or []
    pitfalls = t.get("pitfalls") or []
    lines = [
        "【推理类型】%s（%s）" % (t.get("name") or t.get("id"), t.get("name_en") or t.get("id")),
        "【这一类型适用】%s" % (t.get("when") or "（未填写）"),
        "",
        "【请按下面的步骤走，一步一步来，每次只做一步】",
    ]
    for i, s in enumerate(steps, 1):
        lines.append("%d. %s" % (i, s))
    if not steps:
        # 空 steps 也得给一条，否则提示词里「请按下面的步骤走」后面什么都没有 ——
        # 模型会把它当成「没有约束」，直接给整段答案（这正是脚手架要防的事）。
        lines.append("1. 先把问题里的已知条件逐条列出，再决定下一步做什么。")
    lines += ["", "【必须避免】"]
    if pitfalls:
        for p in pitfalls:
            lines.append("- %s" % p)
    else:
        lines.append("- 不要一次给出全部答案，也不要跳步。")
    lines += [
        "",
        "【问题】",
        q or "(空问题)",
        "",
        "【作答要求】",
        "请**分步作答**：严格按上面的编号一步一步写，每一步都要标出依据",
        "（用了哪条已知条件、哪条假设、还是哪一步计算），不许跳步、不许合并步骤；",
        "写完后单独用一句话说明：这几步里你最没把握的是哪一步，以及为什么。",
    ]
    return "\n".join(lines)


# ------------------------------------------------------------------ ③ 追加（越用越大）
def add(template, save=True):
    """追加一个模板（**同 id 覆盖**），返回合并后的完整模板；`save=True` 时落盘。

    行为逐条定死，全部为了「绝不抛」这一条硬要求：
      · 缺字段补默认值：steps / pitfalls / keywords 至少是空列表，
        name / name_en 缺失时用 id 顶上，when 缺失时给一句占位说明；
      · id 缺失或不合法（不是英文蛇形小写）→ 用 `_fallback_id()` 造一个可用的兜底 id；
      · 同 id 已存在（不论在内置还是追加里）→ 以**已有的那条为底**合并，
        本调用传入的字段覆盖上去，返回合并后的完整模板；
      · `template` 根本不是 dict → 当成「空模板」处理（补一套默认值），
        因为在这里抛异常等于把用户刚写的东西整条丢掉，而它只差几个默认值。
    落盘失败（磁盘满 / 权限）也只返回内存里的结果，**绝不抛** ——
    数据已经在内存库里有用了，不给用户留下一个「全丢了」的印象。
    """
    _ensure_loaded()
    src = dict(template) if isinstance(template, dict) else {}
    tid = _valid_id(src.get("id")) or _fallback_id(src)
    base = _EXTENDED.get(tid)
    if base is None:
        base = _BY_ID.get(tid)
    merged = _copy_template(base) if base else {}
    for k, v in src.items():
        if isinstance(k, str):
            merged[k] = v          # 原样收下（含未知字段），归一化和补默认值交给 _fill
    merged["id"] = tid
    _fill(merged)
    # dict 赋值语义：id 已存在时**保持原来的位置**，新 id 追加到末尾 ——
    # 于是「追加顺序」被完整保留，_merged_raw() 的顺序确定，pick 也确定。
    _EXTENDED[tid] = merged
    try:
        append_jsonl(boost_path(_TEMPLATES_LOG), {
            "ts": now(), "action": "add", "id": tid,
            "requested_id": norm(src.get("id")),   # 记下用户原本想要的 id，便于排查拼写问题
            "steps": len(merged["steps"]), "keywords": len(merged["keywords"]),
            "save": bool(save),
        })
    except Exception:      # noqa: silent-ok — 追加流水失败不能影响「模板已经收下」这个事实
        pass
    if save:
        save_extended()
    return _copy_template(merged)


def all_templates():
    """内置 + 追加的**合并**结果（同 id 时追加的覆盖内置）；每一项都是**副本**。

    为什么必须返回副本：这是唯一一个把整个库交出去的接口，
    调用方（上层拼提示词、自测、界面展示）拿到后随手 `t["steps"].append(...)`
    是非常自然的事 —— 不复制就等于把库的修改权交给了每一个调用点。
    """
    _ensure_loaded()
    return [_copy_template(t) for t in _merged_raw()]


def stats():
    """给日志/自测用的概览（**全部是真实统计**，没有就写 0）。

    至少含 total / builtin / extended / with_keywords / extended_path；
    另外两项（pick_total / extended_file_exists）是为了让自测一条命令
    就能验「真的用起来了、真的落盘了」，不用再去翻文件。
    本函数**读不到文件也不抛**（read_jsonl 自身已容错，这里再兜一层）。
    """
    _ensure_loaded()
    merged = _merged_raw()
    path = boost_path(_TEMPLATES_FILE)
    picks = 0
    try:
        for row in read_jsonl(boost_path(_EVENTS_FILE)):
            if norm(row.get("event")) == "pick":
                picks += 1
    except Exception:      # noqa: silent-ok — 数不出一共选过几次不影响其它统计
        picks = 0
    try:
        exists = bool(os.path.exists(path))
    except Exception:      # noqa: silent-ok — 路径探测失败只当作「没文件」
        exists = False
    with_kw = 0
    for t in merged:
        if t.get("keywords"):
            with_kw += 1
    return {
        "total": len(merged),
        "builtin": len(TEMPLATES),
        "extended": len(_EXTENDED),
        "with_keywords": with_kw,
        "extended_path": path,
        "pick_total": int(picks),
        "extended_file_exists": exists,
    }


# ------------------------------------------------------------------ ④ 落盘
def load_extended():
    """读 `logs/boost/templates.json` 的追加部分，返回 list[dict]。

    · 文件不存在 / 坏了 / 结构不对 → 一律返回 `[]`，**绝不抛**
      （读不出来等价于「还没有追加过」，这是完全正常的状态）；
    · 只读，不创建、不修改、不删除任何文件；
    · 结构校验刻意做得宽：只要是个 dict 且有合法 id 就收下，其余字段由 `_fill` 补，
      因为「用户手写 JSON 少了一个字段」不该导致整条模板被丢掉 —— 那是数据丢失。
    """
    raw = read_json(boost_path(_TEMPLATES_FILE), default=None)
    if not isinstance(raw, dict):
        return []
    items = raw.get("templates")
    if not isinstance(items, list):
        return []
    out, seen = [], set()
    for it in items:
        if not isinstance(it, dict):
            continue
        tid = _valid_id(it.get("id"))
        if not tid or tid in seen:
            continue          # 无 id / id 非法 / 重复：跳过这一条，但不影响其它条
        seen.add(tid)
        row = dict(it)
        row["id"] = tid
        out.append(_fill(row))
    return out


def save_extended(templates=None):
    """把追加部分写进 `logs/boost/templates.json`（`{"version", "templates", "updated_at"}`）。

    · 不传参 → 写**当前内存里的追加部分**（这是 add() 的落盘路径）；
    · 传了 `templates` → 写传入的那一批（顺序即列表顺序，用于导入/测试）；
    · 返回 True/False。写失败不抛，只返回 False —— 数据还在内存库里有用的。
    · **只覆盖内容或直接创建**：不写 tmp、不 rename、不删除任何文件（项目红线）。
    【为什么写之前先 `_ensure_loaded()`】
        否则「进程刚起来、还没读过盘就调 save_extended()」会把磁盘上已有的追加
        用一个空列表**覆盖掉** —— 那是一次静默的数据删除，
        正好踩中最不能踩的那条红线。这一行就是防这个的。
    """
    _ensure_loaded()
    if templates is None:
        items = [_copy_template(t) for t in _EXTENDED.values()]
    else:
        items = []
        for t in (list(templates) if isinstance(templates, (list, tuple)) else []):
            if not isinstance(t, dict):
                continue
            tid = _valid_id(t.get("id")) or _fallback_id(t)
            row = _copy_template(t)
            row["id"] = tid
            items.append(_fill(row))
    payload = {"version": EXTENDED_VERSION,
               "templates": items,
               "updated_at": float(now())}
    try:
        boost_dir()           # 目录不在就先建（建不出来也由 write_json 兜底）
        return bool(write_json(boost_path(_TEMPLATES_FILE), payload))
    except Exception:      # noqa: silent-ok — 落盘失败只是「这次没记住」，不能连累调用方
        return False


