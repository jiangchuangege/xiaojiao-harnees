# 小焦系统本身不依赖任何具体模型。
# 它是完整的载体（器官齐全），模型是火种（可替换）。
# 接入任何模型 → 系统活；换任何模型 → 系统不变。
# 这就是"模型平等"和"变形金刚"的工程基础。
"""小焦 · 载体层 · 元推理模板库（模块 10.1）

【这段为什么这么设计】
    4B 模型最大的毛病不是「算不出来」，而是**不知道该用哪种想法去想**。
    问它一道需要归纳的题，它会写成散文；需要反证，它正面硬证；
    需要枚举，它举三个例子就说「等等」。换成 70B 只是把这类错误压低一点，
    **毛病本身一模一样** —— 因为这不是智力问题，是「没有脚手架」的问题。
    所以本模块不教模型「答案是什么」（那是它的本分，也是它真正擅长的），
    只做它做不好的那件事：**用纯规则判断这道题属于哪种推理类型，
    再把该类型的脚手架递过去**。载体负责「该怎么想」，模型负责「这一小步」。

    具体分成四件事，缺任何一件，这个库就退化成一份普通提示词列表：
      ① TEMPLATES  37 个推理模板（**载体资产**：纯 Python 数据，不依赖任何模型）；
      ② pick()     纯规则选型：关键词命中 + 句式规则加分，得分最高者胜；
      ③ render()   把模板渲染成「分步指令 + 必避坑 + 原问题」的提示词；
      ④ add() / save_extended()  每次追加都落盘 —— 公式④「越用越大」的落地点。

【去掉它会怎样】
    · 去掉 pick()：上层只能把问题原样丢给模型，模型就按自己的偏好走
      （几乎总是「直接给答案」）—— 下面这 37 条模板一条也用不上，白写；
    · 只留关键词、去掉句式规则：`为什么天会下雨` 这类不含模板专有名词的
      问句一个模板都命中不了 → 返回 None → 上层拿不到脚手架，等于没做；
    · 去掉落盘：模板永远只有写死在内置表里的那些，
      用户自己踩出来的推理套路（「我这行得先看量纲再算」）永远进不来 ——
      **「越用越大」这条公式直接失效**，本模块跟一份静态 prompt 手册再无区别。

【为什么 pick() 坚持「没有信号就返回 None」，绝不硬塞一个模板】
    硬塞的代价是双向的：选错模板 → 模型被引到错误方向，
    而它的输出**看起来反而更专业**（有编号、有依据、有条理），
    却是在认真地把错事做完整 —— 这比「没有脚手架」危险得多，
    因为上层和用户都不容易发现。所以判据定死：
    既没有关键词命中、也没有句式命中 → `None`，交给上层（causal / vague 等）接手。
    **宁可空手，不可带错路。**

【为什么 render() 在模板 id 不存在时选「明确报错提示词」，而不是静默退化】
    规格给了两个选项，这里选**第一个：明确说找不到**（同时报出可用模板数量），
    并把 `question` 原文一并附在后面。理由：
      · 静默退化（随便挑一个模板渲染）会把「上层传错 id」这类必然发生的代码错误
        永久藏起来 —— pick() 的返回值是给上层用的，id 拼错必须**当场可见**，
        报错提示词进到日志/自测里一眼就能发现，而找个模板糊上去则一辈子查不出来；
      · 但也不能只报错不留问题：上层这时候往往已经没法再选一次型了，
        留一句「请针对下面的问题直接作答」能让这一轮对话还能继续，
        否则模型对着一整段纯报错文本会开始自己编。二者兼顾，且**绝不抛异常**。

【为什么关键词命中要按长度加权（见 `_kw_weight`）】
    `从`（2 字以内）和 `有多少种` 都只算一次命中，但诊断力天差地别：
    前者在中文里几乎无处不在（任何一句话都可能碰到它），
    后者几乎只出现在枚举类问题里。不加权的结果是
    **谁的关键词表里塞的短字多，谁就永远赢选型** ——
    而这恰恰是「错得看起来很有道理」的主要来源。加权规则见 `_kw_weight`。

【为什么追加部分要另存一个文件，而不是直接改这个 .py】
    · 用户/上层追加的模板是**数据**（随使用增长），内置表是**代码**（随版本走）。
      混在一起写进同一个文件的后果是：升级一次内置表，用户的追加就被冲没了；
    · 所以 `logs/boost/templates.json` 只存「追加部分」，
      读取时**追加覆盖内置**（同 id 以追加的为准）；
    · 每次写它，还额外往 `logs/boost/templates.jsonl` 追加一行流水：
      templates.json 是覆盖写，历史上被覆盖掉的模板不会留痕，
      而项目红线是**绝不删数据**，追加流水让「什么时候加过哪个模板」永远可查。
    · 全程只有 open(w) / open(a)，**没有任何 remove / unlink / rename**。

【为什么不提供 reset / clear 之类的接口】
    规格明确不要，这里也认同：清空 extended 的接口存在一天，
    就迟早会被某个「我没想删数据，只是想重来一次」的调用点用上。
    不留这个口子，就从根上不可能发生这件事。

【与其它模块的关系（不重复造轮子）】
    · 上游是 `vague.py`（判该不该反问）与 `causal.py`（长链因果）；
      本模块只回答「该用哪种想法」，不建图、不检索、不调模型；
    · 下游是 `deepthink.py` —— 它拿这里渲染出来的提示词去真正跑 CoT / ToT；
    · 公共工具全部来自 `core/boost/__init__.py`：
      norm / hits / has_any / cjk_count / note / boost_path / boost_dir，
      口径与其它六个模块**强制一致**（散开写的必然结果是同一句话两处结论不同）。
"""
